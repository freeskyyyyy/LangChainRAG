"""
提示词模板 —— 决定模型"怎么回答"的关键

================================================================
【提示词为什么这么重要】
================================================================
同一个模型，同样的资料，提示词写得好不好，回答质量能差出好几倍。

本项目要在提示词里解决四个问题：

  ① **优先基于资料回答**
     商品、价格、库存等知识库专属信息必须以检索资料为准；资料不足时，
     可以调用模型通用知识，但要明确标注依据。

  ② **必须标注引用**
     回答里的每句话要能对应到具体资料。这样用户能验证、能追溯，
     也让"胡说八道"无处遁形——因为标不出引用就说明没依据。

  ③ **资料不足时可用通用知识回答**
     不能把模型知识伪装成知识库内容；可能过时或依赖具体商品的信息要提醒用户核实。

  ④ **多轮对话要能理解指代**
     "它多少钱"里的"它"指什么，要靠历史对话来消解。

================================================================
【几个具体的提示词技巧】
================================================================
1. **给资料编号 [1] [2]**
   让模型能"指着编号说话"，前端就能把 [1] 变成可点击的引用卡片。

2. **把资料放在问题前面**
   模型对"最近看到的内容"记忆更牢。资料在前、问题在后，
   能提高模型使用资料的意愿（这个现象叫"近因效应"）。

3. **明确要求"引用要出现在句子末尾"**
   不指定的话，模型可能把引用堆在最后一段，
   就没法做到"每句话可追溯"了。

4. **区分知识来源**
   资料不足时明确说明答案来自通用知识，避免用户误认为内容出自自己的知识库。
"""

from __future__ import annotations

from typing import Any

from langchain_core.prompts import ChatPromptTemplate

# ==================================================================
# 系统提示词 —— 定义模型的身份和行为准则
# ==================================================================
SYSTEM_PROMPT = """你是一位专业的问答助手。你可以综合知识库资料和自己的通用知识回答用户问题，但必须如实区分信息来源。

## 回答规则

1. **优先依据知识库**
   当下面的参考资料与问题直接相关时，商品信息、价格、库存、售后政策等专属事实必须以资料为准，不能用通用知识覆盖或推测。

2. **资料不足时使用通用知识**
   如果参考资料为空，或没有直接回答问题所需的信息，请基于你的通用知识尽力回答，并在答案开头明确写「按通用知识回答：」。不要假装答案来自知识库，也不要编造资料库里的内容。
   对于可能随时间变化、强依赖具体品牌/商品/地区的事实，说明不确定性，并建议用户核实最新信息。

3. **标注知识库引用**
   使用参考资料中的信息时，在相关句子末尾标注来源编号，格式为 [1]、[2]；综合多条资料时写成 [1][3]。通用知识不标注虚构的引用编号。

4. **混合回答时区分依据**
   同一答案既使用资料又使用通用知识时，要让用户能看出各自依据；只给资料支持的句子添加引用。

5. **回答风格**
   简洁、口语化，必要时使用 Markdown 列表。不要重复用户的问题。

## 参考资料

{context}
"""

# ==================================================================
# 用户提示词模板
# ==================================================================
USER_PROMPT = """{question}"""

# ==================================================================
# 无资料兜底回答
# ==================================================================
NO_CONTEXT_ANSWER = "抱歉，知识库中没有找到相关信息。"

# 检索分数低于阈值时用的提示（比"没找到"更友好一点）
LOW_CONFIDENCE_ANSWER = (
    "抱歉，知识库中没有找到与这个问题直接相关的资料。\n\n"
    "你可以：\n"
    "- 换一种说法，或补充更多信息\n"
    "- 提问时说得更具体一些（例如商品型号）\n"
    "- 联系人工客服进一步咨询"
)


def build_context(chunks: list[dict[str, Any]], max_chunks: int = 5) -> str:
    """
    把检索到的片段组装成"参考资料"文本。

    【为什么要带文件名和页码】
    模型虽然不直接展示这些，但看到"[1] 来源：iPhone说明书.pdf 第3页"
    这样的格式，会更容易理解"这是一份真实存在的文档"，
    从而更倾向于严格依据资料回答，而不是自由发挥。

    【为什么优先用 parent_content（父块）而不是 content（子块）】
    这就是父子文档策略的收口：子块是用来检索的（小而准），
    父块是用来喂给模型的（大而全）。
    在这里把父块交给模型，模型才能看到完整的上下文。

    【为什么要限制片段数量】
    每多一条资料就多消耗 token（要花钱）。而且资料太多时，
    模型会"抓不住重点"——信息过载反而降低回答质量。
    所以只取最相关的几条。
    """
    if not chunks:
        return "（暂无参考资料）"

    parts: list[str] = []

    for i, chunk in enumerate(chunks[:max_chunks], start=1):
        # 优先用父块（上下文完整），没有就退回子块
        text = chunk.get("parent_content") or chunk.get("content") or ""
        text = text.strip()
        if not text:
            continue

        # 组装来源标注
        source = chunk.get("file_name", "未知文档")
        page = chunk.get("page")
        sheet = chunk.get("sheet_name")

        location = ""
        if page:
            location = f" 第{page}页"
        elif sheet:
            location = f" 工作表「{sheet}」"

        # 加上相似度分数（对模型是个"可信度提示"，实测有助于它优先采纳高分资料）
        score = chunk.get("rerank_score") or chunk.get("rrf_score") or chunk.get("score")
        score_hint = ""
        if isinstance(score, (int, float)):
            # 归一化到 0~1 之间显示，避免不同来源的量纲差异造成误导
            normalized = min(1.0, max(0.0, float(score)))
            score_hint = f" 相关度{normalized:.2f}"

        parts.append(
            f"[{i}] 来源：{source}{location}{score_hint}\n{text}"
        )

    return "\n\n---\n\n".join(parts)


# ==================================================================
# 提示词模板对象
# ==================================================================
def build_rag_prompt() -> ChatPromptTemplate:
    """
    构建 RAG 提示词模板。

    【{context} 和 {question} 这两个占位符】
    它们在运行时会被填上具体的资料和问题。
    ChatPromptTemplate 的 from_messages 会解析这些花括号。

    ⚠️ 注意：系统提示词里如果出现其他花括号（比如 JSON 示例），
    会被误认为占位符而报错。所以这里刻意避免了多余的 {}。
    """
    return ChatPromptTemplate.from_messages(
        [
            ("system", SYSTEM_PROMPT),
            ("human", USER_PROMPT),
        ]
    )


def build_rewrite_prompt() -> ChatPromptTemplate:
    """
    构建"问题改写"用的提示词模板。

    用途：多轮对话时，把带指代的问题补全。
        用户上句问"iPhone 16 怎么样"，这句问"它多少钱"
        → 改写成"iPhone 16 多少钱"

    为什么要这样？因为检索是"无记忆"的——
    拿"它多少钱"去检索，什么也搜不到。
    """
    system = """你是一个查询改写助手。你的任务是把用户的最新问题改写成一个**完整、独立、可检索**的问题。

## 改写规则

1. 补全代词指代：把"它""这个""那个"替换成具体的事物名称
2. 补全省略的信息：如果问题缺少主语或对象，从历史对话中找出来补上
3. 保留原意：不要改变用户想问的内容，不要添加用户没问的方面
4. 只输出改写后的问题，不要有任何解释、前缀或标点修饰
5. 如果最新问题本身已经完整独立（没有指代和省略），原样输出即可

## 历史对话

{history}

## 用户最新问题

{question}

## 改写后的问题"""

    return ChatPromptTemplate.from_messages([("system", system)])


def format_history(messages: list[dict[str, str]], max_turns: int = 3) -> str:
    """
    把历史消息整理成文字，供改写提示词使用。

    【为什么只取最近几轮】
    历史太长会：① 消耗大量 token ② 引入无关信息干扰判断。
    指代通常只跨一到两轮，取最近 3 轮足够。

    另外，**用户的提问比 AI 的回答更重要**——
    因为指代的对象通常出现在用户之前的提问里。
    所以这里对用户提问做了标记，让模型更容易找到指代对象。
    """
    if not messages:
        return "（无历史对话）"

    recent = messages[-(max_turns * 2):]

    lines: list[str] = []
    for msg in recent:
        role = msg.get("role", "")
        content = (msg.get("content") or "").strip()
        if not content:
            continue

        # 太长的消息截断，避免占满提示词
        if len(content) > 300:
            content = content[:300] + "…"

        if role == "user":
            lines.append(f"用户问：{content}")
        else:
            lines.append(f"客服答：{content}")

    return "\n".join(lines) if lines else "（无历史对话）"
